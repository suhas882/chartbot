from pathlib import Path
from typing import Dict, Any, List
from app.config import RAW_DOCS_DIR, REPORTS_DIR

class ToolRegistry:
    """
    Whitelisted registry of local agent tools with rigid parameter validation.
    Categorizes tools into READ_ONLY (safe) and MUTATING (requires HITL approval).
    """

    TOOLS = {
        "search_knowledge_base": {
            "type": "READ_ONLY",
            "description": "Searches the local ChromaDB and BM25 knowledge store for evidence chunks.",
            "parameters": {
                "query": {"type": "string", "description": "The search topic or question."}
            }
        },
        "list_available_documents": {
            "type": "READ_ONLY",
            "description": "Lists all documents currently indexed in the local data repository.",
            "parameters": {}
        },
        "create_summary_report": {
            "type": "MUTATING",
            "description": "Generates and saves a consolidated markdown summary report to the local reports directory.",
            "parameters": {
                "topic": {"type": "string", "description": "Subject title of the report."},
                "content": {"type": "string", "description": "Structured summary text to persist."},
                "filename": {"type": "string", "description": "Target markdown file name (e.g. summary.md)."}
            }
        },
        "purge_document_record": {
            "type": "MUTATING",
            "description": "Permanently deletes a document file and purges all its vectors from ChromaDB.",
            "parameters": {
                "filename": {"type": "string", "description": "Name of the file to remove."}
            }
        }
    }

    @classmethod
    def execute_read_only(cls, tool_name: str, args: Dict[str, Any], vector_store) -> Dict[str, Any]:
        """Executes non-mutating tools autonomously."""
        if tool_name == "list_available_documents":
            docs = vector_store.list_documents()
            return {"status": "SUCCESS", "documents": docs, "count": len(docs)}
            
        elif tool_name == "search_knowledge_base":
            query = args.get("query", "")
            chunks = vector_store.hybrid_search(query)
            return {
                "status": "SUCCESS",
                "chunks": [{"id": c["chunk_id"], "source": c["metadata"].get("source"), "preview": c["content"][:200]} for c in chunks],
                "count": len(chunks)
            }
            
        raise ValueError(f"Tool {tool_name} is not a valid read-only tool.")

    @classmethod
    def execute_mutating(cls, tool_name: str, args: Dict[str, Any], vector_store) -> Dict[str, Any]:
        """Executes mutating tools once human confirmation has been validated."""
        if tool_name == "create_summary_report":
            topic = args.get("topic", "Agent Report")
            content = args.get("content", "No content provided.")
            filename = args.get("filename", "report.md").replace("/", "_").replace("\\", "_")
            if not filename.endswith(".md"):
                filename += ".md"
                
            report_path = REPORTS_DIR / filename
            with open(report_path, "w", encoding="utf-8") as f:
                f.write(f"# {topic}\n\n*Generated by Local Privacy Agent*\n\n{content}\n")
                
            return {
                "status": "SUCCESS",
                "message": f"Successfully created report '{filename}' in local storage.",
                "file_path": str(report_path)
            }

        elif tool_name == "purge_document_record":
            filename = args.get("filename", "")
            if not filename:
                return {"status": "ERROR", "message": "Filename parameter is required."}
                
            # 1. Purge from vector store
            purged_chunks = vector_store.delete_document(filename)
            # 2. Delete raw file if exists
            target_file = RAW_DOCS_DIR / filename
            file_deleted = False
            if target_file.exists():
                target_file.unlink()
                file_deleted = True
                
            return {
                "status": "SUCCESS",
                "message": f"Purged document '{filename}'. Deleted {purged_chunks} vector chunks and file from disk.",
                "file_deleted": file_deleted,
                "purged_chunks": purged_chunks
            }

        raise ValueError(f"Tool {tool_name} is not a valid mutating tool.")
